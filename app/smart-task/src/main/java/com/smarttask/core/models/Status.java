package com.smarttask.core.models;

/**
 * Enumeración que representa los estados del ciclo de vida de una tarea en
 * SmartTask.
 *
 * @author DevAlejandroSaa
 * @version 1.0-SNAPSHOT
 * @since 1.8
 */
public enum Status {
    /**
     * Tarea pendiente o en curso (opción 1).
     */
    ACTIVA,

    /**
     * Tarea finalizada exitosamente (opción 2).
     */
    COMPLETADA
}
