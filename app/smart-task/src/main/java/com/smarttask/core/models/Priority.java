package com.smarttask.core.models;

/**
 * Enumeración que define los niveles de prioridad asignables a una tarea en
 * SmartTask.
 *
 * @author DevAlejandroSaa
 * @version 1.0-SNAPSHOT
 * @since 1.8
 */
public enum Priority {
    /**
     * Prioridad baja (opción 1).
     */
    BAJA,

    /**
     * Prioridad media (opción 2).
     */
    MEDIA,

    /**
     * Prioridad alta (opción 3).
     */
    ALTA
}
